function TabButton({ active, onClick, children }: { active: boolean; onClick: () => void; children: ReactNode }) {
  return (
    <button
      onClick={onClick}
      className={clsx(
        "flex-1 rounded-[6px] py-2 text-xs font-medium transition-colors",
        active ? "bg-graphite-raised text-bone" : "text-slate-dim hover:text-slate",
      )}
    >
      {children}
    </button>
  );
}

function Section({ n, title, children }: { n: number; title: string; children: ReactNode }) {
  return (
    <Card className="space-y-1.5 p-4">
      <p className="text-sm font-semibold text-bone">
        <span className="text-slate-dim">{n}.</span> {title}
      </p>
      <div className="space-y-2 text-sm leading-relaxed text-slate">{children}</div>
    </Card>
  );
}

/** Small numbered sub-clause, e.g. "6.2" — for denser legal-style paragraphs. */
function Clause({ n, children }: { n: string; children: ReactNode }) {
  return (
    <p>
      <span className="text-slate-dim">{n}.</span> {children}
    </p>
  );
}

function PlanSummary() {
  const { data: plans, isLoading } = useQuery({ queryKey: ["plans"], queryFn: listPlans });

  if (isLoading) {
    return (
      <div className="space-y-1.5">
        <Skeleton className="h-16 w-full" />
      </div>
    );
  }
  if (!plans?.length) return null;

  return (
    <div className="space-y-1.5">
      {plans.map((plan) => (
        <div key={plan.id} className="rounded-md border border-hairline bg-graphite-raised p-2.5">
          <div className="flex items-center justify-between">
            <span className="text-xs font-medium text-bone">{PLAN_TITLES[plan.id]}</span>
            <span className="font-mono text-xs text-bone tabular">{rub(plan.price_rub)}</span>
          </div>
          <p className="mt-1 text-[11px] text-slate-dim">
            {formatBytes(plan.storage_limit_bytes)} хранилища · до {plan.ai_calls_limit_per_month} AI-сохранений/мес ·
            до {plan.secrets_limit} записей в Сейфе
          </p>
        </div>
      ))}
    </div>
  );
}

